import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const contractPath = new URL("../docs/api/openapi.json", import.meta.url);
const outputPath = new URL(
  "../packages/api-client-ts/src/generated/schema.ts",
  import.meta.url,
);

const contract = JSON.parse(await readFile(contractPath, "utf8"));
const schemas = contract.components?.schemas ?? {};

const primitive = (schema) => {
  if (!schema) return "unknown";
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.anyOf || schema.oneOf)
    return (schema.anyOf ?? schema.oneOf).map(primitive).join(" | ");
  if (schema.allOf) return schema.allOf.map(primitive).join(" & ");
  if (Array.isArray(schema.type))
    return schema.type
      .map((type) => primitive({ ...schema, type }))
      .join(" | ");
  if (schema.type === "null") return "null";
  if (schema.nullable)
    return `${primitive({ ...schema, nullable: false })} | null`;
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (schema.type === "array") return `(${primitive(schema.items)})[]`;
  if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? []);
    return `{ ${Object.entries(schema.properties ?? {})
      .map(
        ([key, value]) =>
          `${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${primitive(value)}`,
      )
      .join("; ")} }`;
  }
  return (
    {
      string: "string",
      integer: "number",
      number: "number",
      boolean: "boolean",
    }[schema.type] ?? "unknown"
  );
};

const blocks = Object.entries(schemas).map(([name, schema]) => {
  const required = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {})
    .map(
      ([field, value]) =>
        `  ${field}${required.has(field) ? "" : "?"}: ${primitive(value)};`,
    )
    .join("\n");
  return `export type ${name} = {\n${fields}\n};`;
});

const operations = [];
const operationDefinitions = {};
for (const [path, methods] of Object.entries(contract.paths ?? {})) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!operation.operationId) continue;
    if (operationDefinitions[operation.operationId])
      throw new Error(`Duplicate operationId: ${operation.operationId}`);
    operationDefinitions[operation.operationId] = {
      method: method.toUpperCase(),
      path,
    };
    const response = Object.entries(operation.responses ?? {}).find(
      ([status]) => /^2\d\d$/u.test(status),
    )?.[1];
    const responseSchema = Object.values(response?.content ?? {})[0]?.schema;
    const body = Object.values(operation.requestBody?.content ?? {})[0]?.schema;
    operations.push(
      `  ${JSON.stringify(operation.operationId)}: { method: ${JSON.stringify(method.toUpperCase())}; path: ${JSON.stringify(path)}; body: ${body ? primitive(body) : "never"}; response: ${responseSchema ? primitive(responseSchema) : "void"} };`,
    );
  }
}
const generated = await format(
  `// Generated by scripts/generate-api-client.mjs. Do not edit by hand.\n\n${blocks.join("\n\n")}\n\nexport type Operations = {\n${operations.join("\n")}\n};\n\nexport const operationDefinitions = ${JSON.stringify(operationDefinitions)} as const;\n`,
  { parser: "typescript" },
);
const check = process.argv.includes("--check");

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "Generated TypeScript client is stale. Run pnpm api:generate.",
    );
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(
    `Generated API client from ${contractPath.pathname} under ${root}`,
  );
}
