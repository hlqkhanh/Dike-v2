import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const contractPath = new URL("../docs/api/openapi.json", import.meta.url);
const outputPath = new URL(
  "../packages/api-client-ts/src/generated/schema.ts",
  import.meta.url,
);
const operationsPath = new URL(
  "../packages/api-client-ts/src/generated/operations.ts",
  import.meta.url,
);

const contract = JSON.parse(await readFile(contractPath, "utf8"));
const schemas = contract.components?.schemas ?? {};

const primitive = (schema) => {
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (schema.type === "array") return `${primitive(schema.items)}[]`;
  if (schema.type === "object") {
    return schema.additionalProperties
      ? `Record<string, ${primitive(schema.additionalProperties)}>`
      : "Record<string, unknown>";
  }
  return (
    {
      string: "string",
      integer: "number",
      number: "number",
      boolean: "boolean",
    }[schema.type] ?? "unknown"
  );
};

const blocks = Object.entries(schemas).map(([name, schema]) => {
  const required = new Set(schema.required ?? []);
  const hasExplicitRequiredList = Array.isArray(schema.required);
  const fields = Object.entries(schema.properties ?? {})
    .map(([field, value]) => {
      const isRequired = hasExplicitRequiredList
        ? required.has(field)
        : value.nullable !== true;
      return `  ${field}${isRequired ? "" : "?"}: ${primitive(value)};`;
    })
    .join("\n");
  return `export type ${name} = {\n${fields}\n};`;
});

const generated = await format(
  `// Generated by scripts/generate-api-client.mjs. Do not edit by hand.\n\n${blocks.join("\n\n")}\n`,
  { parser: "typescript" },
);
const operationBlocks = Object.entries(contract.paths ?? {}).flatMap(
  ([path, pathItem]) =>
    Object.entries(pathItem).flatMap(([method, operation]) => {
      if (!operation.operationId) return [];
      const requestSchema =
        operation.requestBody?.content?.["application/json"]?.schema;
      const response = Object.entries(operation.responses ?? {}).find(
        ([status]) => /^2\d\d$/u.test(status),
      )?.[1];
      const responseSchema = response?.content?.["application/json"]?.schema;
      const name = operation.operationId;
      const title = name[0].toUpperCase() + name.slice(1);
      return [
        `export const ${name}Operation = { method: "${method.toUpperCase()}", path: "${path}" } as const;\nexport type ${title}OperationRequest = ${requestSchema ? primitive(requestSchema) : "never"};\nexport type ${title}OperationResponse = ${responseSchema ? primitive(responseSchema) : "void"};`,
      ];
    }),
);
const referencedSchemas = new Set();
for (const block of operationBlocks) {
  for (const name of Object.keys(schemas)) {
    if (new RegExp(`\\b${name}\\b`, "u").test(block))
      referencedSchemas.add(name);
  }
}
const operationsGenerated = await format(
  `// Generated by scripts/generate-api-client.mjs. Do not edit by hand.\n\nimport type { ${[...referencedSchemas].sort().join(", ")} } from "./schema";\n\n${operationBlocks.join("\n\n")}\n`,
  { parser: "typescript" },
);
const check = process.argv.includes("--check");

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "Generated TypeScript client is stale. Run pnpm api:generate.",
    );
  }
  const currentOperations = await readFile(operationsPath, "utf8").catch(
    () => "",
  );
  if (currentOperations !== operationsGenerated) {
    throw new Error(
      "Generated TypeScript operations are stale. Run pnpm api:generate.",
    );
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  await writeFile(operationsPath, operationsGenerated, "utf8");
  console.log(
    `Generated API client from ${contractPath.pathname} under ${root}`,
  );
}
